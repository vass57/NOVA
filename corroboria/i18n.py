def translate(locale: str, key: str, **values: object) -> str:
    """Return a translated UI string and fail loudly for missing copy."""

    return TRANSLATIONS[locale][key].format(**values)


def translate_value(locale: str, group: str, value: str) -> str:
    """Translate known pipeline labels while retaining unknown data verbatim."""

    catalogues = {"verdict": VERDICTS, "priority": PRIORITIES, "method": DECISION_METHODS}
    return catalogues[group][locale].get(value, value)
